// Generates src/icon-colors.css: a colour for every lucide icon the app uses (run: node scripts/gen-icon-colors.mjs).
//
// Why a stylesheet and not a prop on 150 icons: icons are drawn by lucide-react in the colour of their text
// (currentColor), mostly set by the parent. This sheet colours them by *what they mean* (money green, travel blue,
// stays teal, time orange, danger red, people violet, messages cyan, charts indigo, ...), in the places where an icon
// was neutral (grey, or the portal accent), and leaves icons that sit on a colour (buttons, gradient tiles, alerts,
// badges) exactly as they are. Navigation chrome (chevrons, arrows, close, menu, loaders) stays neutral on purpose.
// A new icon that is not listed here simply keeps its normal colour.
import { renderToStaticMarkup } from 'react-dom/server';
import { createElement } from 'react';
import * as lucide from 'lucide-react';
import { writeFileSync } from 'node:fs';

